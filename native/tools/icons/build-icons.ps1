<#
.SYNOPSIS
    Turns tools/icon/icons.txt into native/app/gfx/icons.gen.h (name -> path data the Icon widget draws).

.DESCRIPTION
    The C# app's icons are Fluent UI System Icons (MIT) named by the job they do in tools/icon/icons.txt.
    That manifest is the one place a name is tied to a picture, and this script keeps it so: the order,
    the names and each icon's grid (20, 24, ...) come from icons.txt, and the outline comes from the
    Geometry of the same name in the already-generated Icons.xaml, so a run needs no network and gives
    the same bytes every time. (build-icons.ps1 beside icons.txt is what fetches from Fluent.)

    The outline is turned into the Icon widget's float stream: 0 x y (move), 1 x y (line),
    2 x1 y1 x2 y2 x y (cubic), 3 (close). Fluent's paths use only absolute M L H V C Z; anything else
    is an error rather than a silently dropped piece, because a missing piece looks like a design choice.

.EXAMPLE
    pwsh native/tools/icons/build-icons.ps1
#>
[CmdletBinding()]
param(
    [string] $Manifest = (Join-Path $PSScriptRoot '..\..\..\tools\icon\icons.txt'),
    [string] $Xaml     = (Join-Path $PSScriptRoot '..\..\..\src\BertBrowser.App\Resources\Icons.xaml'),
    [string] $OutFile  = (Join-Path $PSScriptRoot '..\..\app\gfx\icons.gen.h')
)
$ErrorActionPreference = 'Stop'
$inv = [System.Globalization.CultureInfo]::InvariantCulture

$entries = Get-Content -LiteralPath $Manifest |
    Where-Object { $_.Trim() -and -not $_.TrimStart().StartsWith('#') } |
    ForEach-Object {
        $f = $_ -split '\|' | ForEach-Object { $_.Trim() }
        if ($f.Count -ne 4) { throw "icons.txt: expected 'Name | Folder | file | size', got '$_'" }
        if ($f[0] -notmatch '^[A-Za-z][A-Za-z0-9]*$') { throw "icons.txt: '$($f[0])' is not a C++ identifier" }
        [pscustomobject]@{ Name = $f[0]; Size = [int]$f[3] }
    }
$dupes = $entries | Group-Object Name | Where-Object Count -gt 1
if ($dupes) { throw "icons.txt: duplicate name(s): $($dupes.Name -join ', ')" }

$geo = @{}
foreach ($m in [regex]::Matches((Get-Content -LiteralPath $Xaml -Raw), '<Geometry x:Key="Icon\.([A-Za-z0-9]+)">([^<]+)</Geometry>')) {
    $geo[$m.Groups[1].Value] = $m.Groups[2].Value.Trim()
}

function Num([double] $v) {
    $s = $v.ToString('0.#####', $inv)
    if ($s -eq '-0') { $s = '0' }
    if ($s.Contains('.')) { return "${s}f" }
    return "$s.f"
}

function Convert-IconPath([string] $name, [string] $data) {
    if (-not $data.StartsWith('F1 ')) { throw "${name}: expected the nonzero fill rule (F1), got '$($data.Substring(0, 3))'" }
    $tokens = @([regex]::Matches($data.Substring(3), '[A-Za-z]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?|\S') | ForEach-Object { $_.Value })
    $out = [System.Collections.Generic.List[string]]::new()
    $st = @{ i = 0 }
    $rd = {
        if ($st.i -ge $tokens.Count) { throw "${name}: path ends mid-command" }
        $v = [double]::Parse($tokens[$st.i], $inv)
        $st.i++
        $v
    }
    $cx = 0.0; $cy = 0.0; $cmd = ''
    while ($st.i -lt $tokens.Count) {
        $t = $tokens[$st.i]
        if ($t -match '^[A-Za-z]$') {
            if ($t -notmatch '^[MLHVCZ]$') { throw "${name}: unsupported path command '$t'" }
            $cmd = $t
            $st.i++
            if ($t -eq 'Z') { $out.Add('3.f'); $cmd = ''; continue }
        } elseif ($cmd -eq '') { throw "${name}: number with no command" }
        switch ($cmd) {
            'M' { $cx = & $rd; $cy = & $rd; $out.Add("0.f,$(Num $cx),$(Num $cy)"); $cmd = 'L' }
            'L' { $cx = & $rd; $cy = & $rd; $out.Add("1.f,$(Num $cx),$(Num $cy)") }
            'H' { $cx = & $rd; $out.Add("1.f,$(Num $cx),$(Num $cy)") }
            'V' { $cy = & $rd; $out.Add("1.f,$(Num $cx),$(Num $cy)") }
            'C' {
                $a = & $rd; $b = & $rd; $c = & $rd; $d = & $rd; $cx = & $rd; $cy = & $rd
                $out.Add("2.f,$(Num $a),$(Num $b),$(Num $c),$(Num $d),$(Num $cx),$(Num $cy)")
            }
        }
    }
    return $out
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// GENERATED by native/tools/icons/build-icons.ps1 from tools/icon/icons.txt. Do not edit by hand:')
[void]$sb.AppendLine('// change the manifest and re-run the script. Artwork is Fluent UI System Icons, MIT licensed:')
[void]$sb.AppendLine('// https://github.com/microsoft/fluentui-system-icons')
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('#include "ui/controls.h"')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('#include <cstring>')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace bb::icons {')
[void]$sb.AppendLine('namespace data {')
foreach ($e in $entries) {
    if (-not $geo.ContainsKey($e.Name)) { throw "$($e.Name): in icons.txt but not in Icons.xaml -- run tools/icon/build-icons.ps1 first" }
    $cmds = Convert-IconPath $e.Name $geo[$e.Name]
    [void]$sb.AppendLine("inline constexpr float k$($e.Name)[] = {")
    $line = '   '
    foreach ($c in $cmds) {
        if ($line.Length + $c.Length -gt 118) { [void]$sb.AppendLine($line); $line = '   ' }
        $line += " $c,"
    }
    [void]$sb.AppendLine($line)
    [void]$sb.AppendLine('};')
}
[void]$sb.AppendLine('}  // namespace data')
[void]$sb.AppendLine('')
foreach ($e in $entries) {
    [void]$sb.AppendLine("inline constexpr ui::IconData $($e.Name){$($e.Size).f, data::k$($e.Name), sizeof(data::k$($e.Name)) / sizeof(float)};")
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('struct NamedIcon {')
[void]$sb.AppendLine('    const char* name;')
[void]$sb.AppendLine('    const ui::IconData* icon;')
[void]$sb.AppendLine('};')
[void]$sb.AppendLine('inline constexpr NamedIcon kAll[] = {')
foreach ($e in $entries) { [void]$sb.AppendLine("    {`"$($e.Name)`", &$($e.Name)},") }
[void]$sb.AppendLine('};')
[void]$sb.AppendLine('inline constexpr size_t kCount = sizeof(kAll) / sizeof(kAll[0]);')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('// By manifest name; null when there is no such icon (a name from data, e.g. a command bar item).')
[void]$sb.AppendLine('inline const ui::IconData* find(const char* name) {')
[void]$sb.AppendLine('    for (const NamedIcon& n : kAll) {')
[void]$sb.AppendLine('        if (std::strcmp(n.name, name) == 0) return n.icon;')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('    return nullptr;')
[void]$sb.AppendLine('}')
[void]$sb.AppendLine('}  // namespace bb::icons')

$resolved = [System.IO.Path]::GetFullPath($OutFile)
[System.IO.File]::WriteAllText($resolved, $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))
Write-Host "Wrote $($entries.Count) icons to $resolved"
