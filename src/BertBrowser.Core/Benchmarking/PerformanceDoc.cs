using System.Globalization;
using System.Text;

namespace BertBrowser.Core.Benchmarking;

/// <summary>
/// Renders <c>docs/performance.md</c> from the committed baselines — the public evidence for the
/// README's "fast and efficient", regenerated rather than written.
/// </summary>
/// <remarks>
/// Ordering is fixed (machine key, then tier, then id) so that re-running it after a baseline
/// changes produces a diff of exactly the numbers that moved.
/// </remarks>
public static class PerformanceDoc
{
    public const string Header = "<!-- Generated by `BertBrowser.Bench report` from bench/baselines/*.json. Do not edit by hand. -->";

    public static string Render(IReadOnlyList<BenchResultSet> baselines, string commandsSection)
    {
        var sb = new StringBuilder();
        sb.AppendLine(Header);
        sb.AppendLine("# Performance");
        sb.AppendLine();
        sb.AppendLine("Every number here was produced by `tools/BertBrowser.Bench` and recorded as a baseline under");
        sb.AppendLine("`bench/baselines/`. Later runs on the same machine are compared against that file; CI compares");
        sb.AppendLine("allocations on every push. See `bench/README.md` for the workflow.");
        sb.AppendLine();
        sb.AppendLine("## How to run");
        sb.AppendLine();
        sb.AppendLine(commandsSection.TrimEnd());
        sb.AppendLine();

        if (baselines.Count == 0)
        {
            sb.AppendLine("_No baselines recorded yet._");
            sb.AppendLine();
        }

        foreach (var set in baselines.OrderBy(b => b.Machine.Key, StringComparer.Ordinal).ThenBy(b => b.Run.Real))
        {
            sb.Append("## ").Append(set.Machine.Key);
            if (set.Run.Real) sb.Append(" (real data)");
            sb.AppendLine().AppendLine();

            sb.AppendLine("| | |");
            sb.AppendLine("|---|---|");
            sb.Append("| CPU | ").Append(set.Machine.Cpu).Append(", ").Append(set.Machine.LogicalCores).AppendLine(" logical cores |");
            sb.Append("| RAM | ").Append(set.Machine.RamGb).AppendLine(" GB |");
            sb.Append("| Windows build | ").Append(set.Machine.OsBuild).AppendLine(" |");
            sb.Append("| .NET | ").Append(set.Machine.Runtime).AppendLine(" |");
            if (set.Machine.PowerPlan is not null) sb.Append("| Power plan | ").Append(set.Machine.PowerPlan).AppendLine(" |");
            sb.Append("| Corpus | ").Append(set.Run.Real ? "the machine's own index and folders" : $"synthetic, scale {set.Run.Scale} ({set.Run.Scale * 100_000:N0} rows)").AppendLine(" |");
            sb.Append("| Job | ").Append(set.Run.Job).Append(set.Run.Toolchain is { } tc ? $", {tc} toolchain" : "").AppendLine(" |");
            sb.Append("| Recorded | ").Append(set.GeneratedUtc.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture))
              .Append(" at `").Append(Short(set.Git.Sha)).Append('`').Append(set.Git.Dirty ? " (uncommitted changes)" : "").AppendLine(" |");
            sb.AppendLine();

            BenchMarkdown.AppendTierTables(sb, set.Benchmarks);
        }

        sb.AppendLine("## What the numbers do and do not mean");
        sb.AppendLine();
        sb.AppendLine("- **Tier A** is BenchmarkDotNet over `BertBrowser.Core` with a synthetic corpus unless marked real.");
        sb.AppendLine("  Disk-reading benchmarks run against files the OS has cached, so they measure the code, not the disk.");
        sb.AppendLine("  `Allocated/op` is exact for pure code; benchmarks over SQLite, the thread pool or disk declare a");
        sb.AppendLine("  tolerance, which the compare tool honours.");
        sb.AppendLine("- **Tier B** drives the real window offscreen under WPF's software rasteriser, parked outside every");
        sb.AppendLine("  monitor at 1400×900. It is a regression signal for view-model and layout work, not the GPU path a");
        sb.AppendLine("  user sees. A `search.*` time includes the 200 ms typing debounce. Each scenario is a fresh process.");
        sb.AppendLine("- **Tier C** launches the built `BertBrowser.exe` against a scratch data directory and reads marks the");
        sb.AppendLine("  app writes under `BERTBROWSER_STARTUP_TRACE`. The window is parked offscreen and the post-window");
        sb.AppendLine("  side effects (index-helper attach, change-log policy, update check) are skipped, so the headline is");
        sb.AppendLine("  \"process start to first listing\", not \"to idle\". The first launch is discarded as cold.");
        sb.AppendLine("- Medians are reported because a single slow sample is the machine, not the code; p95 is nearest-rank.");
        sb.AppendLine();

        return sb.ToString();
    }

    private static string Short(string sha) => sha.Length > 9 ? sha[..9] : sha;
}
