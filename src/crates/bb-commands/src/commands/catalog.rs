//! Every command the app has, in the order the palette's "Browse all commands" and the Keyboard page
//! list them. An id here with no handler in the UI (or the reverse) fails when the registry is
//! built, so a command cannot be listed and do nothing. Ids are persisted (keymap overrides, palette
//! pins), so a row may be renamed freely but its id never changes meaning.
//! Spec: Core/Services/Commands/CommandCatalog.cs, CommandDescriptor.cs.

use std::collections::HashMap;
use std::sync::LazyLock;

use super::KeyChord;

/// Where a command's *shortcut* is live. It says nothing about the palette, which can run any
/// available command from anywhere.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum CommandContext {
    /// Always, the settings page included.
    App,
    /// Whenever the folders are showing, but not while the settings page stands in for them.
    Browser,
    /// Only while a file list has the keyboard.
    FileList,
}

/// How readily the palette offers a command nobody asked for by name.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug, Default)]
pub enum CommandProminence {
    /// Eligible for the suggestions an empty palette shows.
    Essential,
    #[default]
    Standard,
    /// Found by typing, ranked behind an equal match.
    Rare,
}

/// One thing the app can be told to do: a stable id, the words the palette and the Keyboard page
/// show, and the shortcut it ships with.
#[derive(Clone, Debug)]
pub struct CommandDescriptor {
    /// Dotted and lowercase (`tab.new`).
    pub id: &'static str,
    pub name: &'static str,
    pub category: &'static str,
    pub context: CommandContext,
    pub icon: Option<&'static str>,
    /// The first is the one menus and tooltips print.
    pub default_chords: Vec<KeyChord>,
    /// Other words people look for it under.
    pub aliases: &'static [&'static str],
    pub prominence: CommandProminence,
}

/// The palette's groups, in the order "Browse all commands" lists them.
pub struct CommandCategories;

