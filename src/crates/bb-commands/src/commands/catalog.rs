static ALL: LazyLock<Vec<CommandDescriptor>> = LazyLock::new(|| {
    ROWS.iter()
        .map(
            |Row(id, name, category, context, icon, keys, prominence, aliases)| CommandDescriptor {
                id,
                name,
                category,
                context: *context,
                icon: if icon.is_empty() { None } else { Some(icon) },
                default_chords: keys.split_whitespace().map(KeyChord::parse).collect(),
                aliases,
                prominence: *prominence,
            },
        )
        .collect()
});

static BY_ID: LazyLock<HashMap<&'static str, usize>> =
    LazyLock::new(|| ALL.iter().enumerate().map(|(i, c)| (c.id, i)).collect());

pub struct CommandCatalog;

impl CommandCatalog {
    pub fn all() -> &'static [CommandDescriptor] {
        &ALL
    }

    /// Exact, case-sensitive.
    pub fn find(id: &str) -> Option<&'static CommandDescriptor> {
        BY_ID.get(id).map(|&i| &ALL[i])
    }

    pub fn is_known(id: &str) -> bool {
        BY_ID.contains_key(id)
    }
}
