<#
.SYNOPSIS
    Turns icons.txt into icons.geo.txt, the committed outline cache build-icons.ps1 reads.

.DESCRIPTION
    Fetches each icon named in the manifest from Fluent UI System Icons (MIT) and writes its outline
    out, one line per icon, keyed by the job it does, so a call site says icons::Back rather than a
    codepoint nobody can read. See icons.txt for why the app stopped using the Segoe font.
    build-icons.ps1 turns the cache into app/gfx/icons.gen.h without a network.

    Nothing here is clever on purpose: an SVG this cannot convert exactly is an error, never a
    silently dropped subpath. A missing piece of an icon looks like a design choice, which is the
    same class of bug -- a wrong picture that compiles -- that the manifest exists to stop.

    Run it when icons.txt changes (then run build-icons.ps1), and commit both outputs. It needs network
    access; the app and build-icons.ps1 never do.

.EXAMPLE
    pwsh tools/icons/fetch-fluent.ps1
    pwsh tools/icons/fetch-fluent.ps1 -WhatIf     # report what would change, write nothing
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [string] $Manifest = (Join-Path $PSScriptRoot 'icons.txt'),
    [string] $OutFile  = (Join-Path $PSScriptRoot 'icons.geo.txt'),
    [string] $Ref      = 'main'
)

$ErrorActionPreference = 'Stop'
$base = "https://raw.githubusercontent.com/microsoft/fluentui-system-icons/$Ref/assets"

$entries = Get-Content -LiteralPath $Manifest |
    Where-Object { $_.Trim() -and -not $_.TrimStart().StartsWith('#') } |
    ForEach-Object {
        $f = $_ -split '\|' | ForEach-Object { $_.Trim() }
        if ($f.Count -ne 4) { throw "icons.txt: expected 'Name | Folder | file | size', got '$_'" }
        [pscustomobject]@{ Name = $f[0]; Folder = $f[1]; File = $f[2]; Size = $f[3] }
    }

$dupes = $entries | Group-Object Name | Where-Object Count -gt 1
if ($dupes) { throw "icons.txt: duplicate name(s): $($dupes.Name -join ', ')" }

Write-Host "Fetching $($entries.Count) icons from fluentui-system-icons@$Ref"

$geometries = foreach ($e in $entries) {
    $url = "$base/$([uri]::EscapeDataString($e.Folder))/SVG/ic_fluent_$($e.File)_$($e.Size)_regular.svg"
    try { $svg = (Invoke-WebRequest -Uri $url -UseBasicParsing).Content }
    catch { throw "$($e.Name): cannot fetch $url -- $($_.Exception.Message)" }

    # Anything that is not a <path d="..."> carries outline this script would drop on the floor.
    $shapes = [regex]::Matches($svg, '<(circle|rect|ellipse|polygon|polyline|line)\b')
    if ($shapes.Count) {
        throw "$($e.Name): $($e.File) uses <$($shapes[0].Groups[1].Value)>, which this script cannot convert. Pick a different asset or extend the script."
    }

    $paths = [regex]::Matches($svg, '<path\b[^>]*?\bd="([^"]+)"[^>]*>')
    if (-not $paths.Count) { throw "$($e.Name): no <path> in $url" }

    # SVG fills nonzero unless told otherwise, so the rule is always stated (F1 nonzero, F0 evenodd).
    # Mixing the two inside one icon cannot be expressed in a single outline.
    $rules = $paths | ForEach-Object { if ($_.Value -match 'fill-rule="evenodd"') { 'F0' } else { 'F1' } } | Select-Object -Unique
    if ($rules.Count -gt 1) { throw "$($e.Name): mixes fill-rule nonzero and evenodd across subpaths; needs a GeometryGroup." }

    $d = ($paths | ForEach-Object { $_.Groups[1].Value.Trim() }) -join ' '
    $d = [regex]::Replace($d, '\s+', ' ')

    [pscustomobject]@{ Name = $e.Name; Data = "$rules $d"; Source = "$($e.Folder)/$($e.File)_$($e.Size)" }
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('# GENERATED by tools/icons/fetch-fluent.ps1 from icons.txt. Do not edit by hand.')
[void]$sb.AppendLine('# Outline cache: Name | Fluent source | fill rule (F1 nonzero) and SVG path data. build-icons.ps1 reads this')
[void]$sb.AppendLine('# so regenerating icons.gen.h needs no network. Artwork is Fluent UI System Icons, MIT licensed:')
[void]$sb.AppendLine('# https://github.com/microsoft/fluentui-system-icons')
foreach ($g in $geometries) {
    [void]$sb.AppendLine("$($g.Name) | $($g.Source) | $($g.Data)")
}

$resolved = [System.IO.Path]::GetFullPath($OutFile)
if ($PSCmdlet.ShouldProcess($resolved, 'write')) {
    [System.IO.File]::WriteAllText($resolved, $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))
    Write-Host "Wrote $($geometries.Count) geometries to $resolved"
} else {
    Write-Host "Would write $($geometries.Count) geometries to $resolved"
}
